data class YearOutline(
    val year: Int,
    val title: String,
    val body: String,
)

data class SlotNumberOverride(
    val slotId: String,
    val repLo: Int? = null,
    val repHi: Int? = null,
    val nSets: Int? = null,
    val name: String? = null,
)

fun applySlotOverrides(
    slots: List<SlotDefinition>,
    overrides: List<SlotNumberOverride>,
): List<SlotDefinition> {
    val byId = overrides.associateBy { it.slotId }
    return slots.map { slot ->
        val override = byId[slot.id] ?: return@map slot
        slot.copy(
            repLo = override.repLo ?: slot.repLo,
            repHi = override.repHi ?: slot.repHi,
            nSets = override.nSets ?: slot.nSets,
            name = override.name ?: slot.name,
        )
    }
}

private fun slot(
    id: String,
    day: Char,
    order: Int,
    name: String,
    kind: SlotKind,
    repLo: Int,
    repHi: Int,
    sets: Int,
    floor: Int,
    substitutes: List<String>,
    equipment: Equipment,
    notes: String,
    perSide: Boolean = false,
    isCarry: Boolean = false,
    optional: Boolean = false,
    tracksLoad: Boolean = true,
    usesTrapBarRir: Boolean = false,
    repStep: Int = 1,
): SlotDefinition {
    return SlotDefinition(
        id = id,
        day = day,
        sortOrder = order,
        name = name,
        kind = kind,
        repLo = repLo,
        repHi = repHi,
        nSets = sets,
        rirFloor = floor,
        substitutes = substitutes,
        isCarry = isCarry,
        isOptional = optional,
        tracksLoad = tracksLoad,
        equipment = equipment,
        perSide = perSide,
        usesTrapBarRir = usesTrapBarRir,
        repStep = repStep,
        notes = notes,
    )
}
